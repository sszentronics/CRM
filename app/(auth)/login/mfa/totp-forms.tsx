"use client";

import { useActionState, useEffect, useState } from "react";
import { FormMessage } from "@/components/features/auth/form-message";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { startTotpEnrollment, verifyTotp, type EnrollResult } from "../../actions";

function CodeForm({ factorId, next }: { factorId: string; next: string }) {
  const [state, action, pending] = useActionState(verifyTotp, null);
  return (
    <form action={action} className="flex flex-col gap-4" noValidate>
      {state?.message && !state.ok && !state.fieldErrors ? <FormMessage tone="error">{state.message}</FormMessage> : null}
      <input type="hidden" name="factorId" value={factorId} />
      <input type="hidden" name="next" value={next} />
      <Input
        label="6-digit code"
        name="code"
        inputMode="numeric"
        autoComplete="one-time-code"
        pattern="\d{6}"
        maxLength={6}
        autoFocus
        className="[&_input]:tl-amount [&_input]:text-title [&_input]:tracking-[0.3em]"
        error={state?.fieldErrors?.code?.[0]}
      />
      <Button type="submit" block disabled={pending}>
        {pending ? "Checking" : "Verify code"}
      </Button>
    </form>
  );
}

export function VerifyTotp({ factorId, next }: { factorId: string; next: string }) {
  return <CodeForm factorId={factorId} next={next} />;
}

export function EnrollTotp({ next }: { next: string }) {
  const [enrolment, setEnrolment] = useState<EnrollResult | null>(null);

  useEffect(() => {
    let live = true;
    startTotpEnrollment().then((r) => {
      if (live) setEnrolment(r);
    });
    return () => {
      live = false;
    };
  }, []);

  if (!enrolment) {
    return <div aria-busy className="h-[200px] w-[200px] animate-pulse rounded-card bg-tl-raised" />;
  }
  if (!enrolment.ok) return <FormMessage tone="error">{enrolment.message}</FormMessage>;

  return (
    <div className="flex flex-col gap-5">
      <div className="flex items-center gap-5">
        {/* The QR code is an SVG data URL generated by Supabase Auth. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={enrolment.qrCode}
          alt="QR code to add Trading Labs CRM to your authenticator app"
          width={168}
          height={168}
          className="rounded-control border border-tl-line bg-white p-2"
        />
        <div className="flex min-w-0 flex-col gap-1">
          <p className="text-label font-medium text-tl-text">Cannot scan it?</p>
          <p className="text-small text-tl-muted">Enter this key in the app instead.</p>
          <code data-testid="totp-secret" className="text-small break-all text-tl-text-2 select-all">
            {enrolment.secret}
          </code>
        </div>
      </div>
      <CodeForm factorId={enrolment.factorId} next={next} />
    </div>
  );
}
